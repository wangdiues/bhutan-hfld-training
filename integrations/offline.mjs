/**
 * Offline support (task M6-05). After the build, writes dist/sw.js: a service worker that
 * precaches every page with its styles, scripts and fonts on the first visit, and caches images,
 * search files and downloads the first time they are used. Pages are fetched network-first,
 * so a connected learner always gets the latest version; offline, the cached copy is shown.
 * Hand-written instead of @vite-pwa/astro, to avoid a dependency for ~60 lines.
 */
import { createHash } from 'node:crypto';
import { readdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const PRECACHE = /\.(html|css|js|woff2|svg|webmanifest)$/;
// Search index fragments, script downloads and slide images are cached on first use instead.
const SKIP = [/^pagefind\//, /^scripts\//, /^downloads\//, /^sw\.js$/];

async function walk(dir) {
	const out = [];
	for (const e of await readdir(dir, { withFileTypes: true })) {
		const p = join(dir, e.name);
		if (e.isDirectory()) out.push(...(await walk(p)));
		else out.push(p);
	}
	return out;
}

/** @param {{ base: string }} options */
export default function offline({ base }) {
	const b = base.replace(/\/?$/, '/');
	return {
		name: 'hfld-offline',
		hooks: {
			'astro:build:done': async ({ dir, logger }) => {
				const root = fileURLToPath(dir);
				const files = (await walk(root))
					.map((f) => relative(root, f).split(sep).join('/'))
					.filter((f) => PRECACHE.test(f) && !SKIP.some((r) => r.test(f)))
					.sort();
				const hash = createHash('sha256');
				let bytes = 0;
				for (const f of files) {
					hash.update(f).update(await readFile(join(root, f)));
					bytes += (await stat(join(root, f))).size;
				}
				// Pages are cached by their directory URL ("day-1/x/"), the way people visit them.
				const urls = files.map((f) => b + f.replace(/(^|\/)index\.html$/, '$1'));
				const version = hash.digest('hex').slice(0, 12);
				await writeFile(join(root, 'sw.js'), serviceWorker(version, b, urls));
				logger.info(`sw.js: ${urls.length} files (${(bytes / 1e6).toFixed(1)} MB) precached, version ${version}`);
			},
		},
	};
}

function serviceWorker(version, base, urls) {
	return `// Generated by integrations/offline.mjs (task M6-05). Do not edit.
const PRECACHE = 'hfld-precache-${version}';
const RUNTIME = 'hfld-runtime';
const URLS = ${JSON.stringify(urls)};

self.addEventListener('install', (event) => {
	event.waitUntil(caches.open(PRECACHE).then((c) => c.addAll(URLS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
	event.waitUntil(
		caches
			.keys()
			.then((keys) => Promise.all(keys.filter((k) => k.startsWith('hfld-precache-') && k !== PRECACHE).map((k) => caches.delete(k))))
			.then(() => self.clients.claim()),
	);
});

self.addEventListener('fetch', (event) => {
	const req = event.request;
	const url = new URL(req.url);
	if (req.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith(${JSON.stringify(base)})) return;
	if (req.mode === 'navigate') {
		// Network first, so connected learners see updates; the cached page when offline.
		event.respondWith(
			fetch(req)
				.then((res) => {
					const copy = res.clone();
					if (res.ok) caches.open(RUNTIME).then((c) => c.put(req, copy));
					return res;
				})
				.catch(() => caches.match(req, { ignoreSearch: true }).then((r) => r || caches.match(${JSON.stringify(base)}))),
		);
		return;
	}
	// Everything else: cache first, then the network (and keep a copy).
	event.respondWith(
		caches.match(req).then(
			(hit) =>
				hit ||
				fetch(req).then((res) => {
					if (res.ok) {
						const copy = res.clone();
						caches.open(RUNTIME).then((c) => c.put(req, copy));
					}
					return res;
				}),
		),
	);
});
`;
}
